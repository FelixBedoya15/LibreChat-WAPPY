export const getCitiesForDepartment = (deptName: string): string[] => {
  if (!deptName) return [];
  const found = COLOMBIA_LOCATIONS.find(
    (loc) => loc.departamento.toLowerCase() === deptName.trim().toLowerCase()
  );
  return found ? found.ciudades : [];
};
